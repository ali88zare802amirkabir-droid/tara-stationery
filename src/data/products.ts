function defineProduct(seed: ProductSeed, index: number): Product {
  const brand = BRAND_NAMES[seed.brandId];
  const hasColorSpec = seed.specs.some((spec) => spec.key.includes('رنگ'));

  return {
    id: `prd_${String(index + 1).padStart(3, '0')}`,
    slug: seed.slug,
    name: seed.name,
    sku: `${BRAND_CODES[seed.brandId]}-${String(index + 1).padStart(4, '0')}`,
    brand,
    categoryId: seed.categoryId,
    price: seed.price,
    comparePrice: seed.comparePrice ?? null,
    stock: seed.stock,
    lowStockThreshold: seed.lowStockThreshold ?? 8,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    soldCount: seed.soldCount,
    images: gallery(seed.art, seed.name),
    shortDescription: seed.shortDescription,
    description: seed.description,
    features: seed.features,
    specifications: seed.specs,
    variants: hasColorSpec
      ? [{ id: `${seed.slug}_color`, name: 'رنگ', values: ['آبی', 'مشکی', 'قرمز', 'سبز'], enabled: true }]
      : [],
    tags: seed.tags,
    featured: seed.flags?.featured ?? false,
    bestseller: seed.flags?.bestseller ?? false,
    newProduct: seed.flags?.newProduct ?? false,
    status: seed.status ?? (seed.flags?.draft ? 'draft' : 'active'),
    createdAt: seed.createdAt,
    updatedAt: seed.createdAt,
    seo: {
      title: `${seed.name} | خرید با قیمت مناسب از تارا`,
      description: seed.shortDescription,
      keywords: [...seed.tags, brand, seed.slug.split('-')[0]].filter(Boolean),
    },
    art: String(seed.art),
  };
}

export const products: Product[] = seeds.map(defineProduct);

export const productBySlug = new Map(products.map((product) => [product.slug, product]));
export const productById = new Map(products.map((product) => [product.id, product]));
